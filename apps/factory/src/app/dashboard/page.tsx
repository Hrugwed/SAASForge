import Link from "next/link";
import { Container } from "@saasforge/ui";
import { SignOutButton } from "@/components/auth/sign-out-button";
import { getControlPlaneSnapshot } from "@/lib/control-plane";
import { requireFactoryOperator } from "@/lib/factory-operator";

export const metadata = {
  title: "Dashboard",
};

const capabilities = [
  { module: "auth", name: "Identity", code: "AUTH", tone: "lime" },
  { module: "billing", name: "Billing", code: "PAY", tone: "violet" },
  { module: "email", name: "Email", code: "MAIL", tone: "orange" },
  { module: "analytics", name: "Analytics", code: "DATA", tone: "blue" },
  { module: "jobs", name: "Jobs", code: "QUEUE", tone: "lime" },
  { module: "storage", name: "Storage", code: "FILES", tone: "violet" },
] as const;

export default async function DashboardPage() {
  const [{ session }, snapshot] = await Promise.all([
    requireFactoryOperator(),
    getControlPlaneSnapshot(),
  ]);
  const firstName = session.user.name.trim().split(/\s+/)[0] || "maker";
  const needsReview =
    snapshot.counts.reviewRequired +
    snapshot.counts.attention +
    snapshot.issues.length;
  const metrics = [
    {
      label: "Validated registry records",
      value: String(snapshot.counts.registered).padStart(2, "0"),
      detail:
        snapshot.counts.registered === 0
          ? "No local products yet"
          : "Read on this server request",
      tone: "orange",
    },
    {
      label: "Manifest matched",
      value: String(snapshot.counts.manifestVerified).padStart(2, "0"),
      detail: "Registry and product agree",
      tone: "lime",
    },
    {
      label: "Needs review",
      value: String(needsReview).padStart(2, "0"),
      detail: "Drift, missing evidence, or registry issues",
      tone: "violet",
    },
    {
      label: "Factory version",
      value: `v${snapshot.factoryVersion}`,
      detail: "Compared with every manifest",
      tone: "blue",
    },
  ];
  const verificationRows = [
    {
      label: "Registry entries",
      detail: `${snapshot.counts.registered} validated local record${snapshot.counts.registered === 1 ? "" : "s"}`,
    },
    {
      label: "Current manifests",
      detail: `${snapshot.counts.tracked} product${snapshot.counts.tracked === 1 ? "" : "s"} on factory ${snapshot.factoryVersion}`,
    },
    {
      label: "Version review",
      detail: `${snapshot.counts.reviewRequired} product${snapshot.counts.reviewRequired === 1 ? "" : "s"} ahead or behind`,
    },
    {
      label: "Registry diagnostics",
      detail:
        snapshot.issues.length === 0
          ? "No registry parsing issues"
          : `${snapshot.issues.length} bounded issue${snapshot.issues.length === 1 ? "" : "s"}`,
    },
  ];

  return (
    <Container className="dashboard-container" id="overview">
      <header className="dashboard-header">
        <div className="dashboard-heading-copy">
          <p>
            <span aria-hidden="true" /> PRIVATE FACTORY / CONTROL PLANE
          </p>
          <h1>Good morning, {firstName}.</h1>
          <span>
            Inspect the products generated by this factory, reconcile their
            manifests, and act on evidence without sharing their production
            boundaries.
          </span>
        </div>
        <div className="dashboard-actions">
          <Link className="dashboard-overview-link" href="/">
            Factory overview <span aria-hidden="true">↗</span>
          </Link>
          <SignOutButton />
        </div>
      </header>

      <section className="metric-grid" aria-label="Factory snapshot">
        {metrics.map((metric, index) => (
          <article
            className="metric-card"
            data-tone={metric.tone}
            key={metric.label}
          >
            <div>
              <span>{String(index + 1).padStart(2, "0")}</span>
              <i aria-hidden="true" />
            </div>
            <strong>{metric.value}</strong>
            <footer>
              <span>{metric.label}</span>
              <small>{metric.detail}</small>
            </footer>
          </article>
        ))}
      </section>

      <section className="dashboard-grid" aria-label="Factory operations">
        <article className="dashboard-panel launch-panel">
          <header className="panel-heading">
            <div>
              <p>01 / PRODUCT PORTFOLIO</p>
              <h2>
                {snapshot.products.length === 0
                  ? "Forge the first product foundation."
                  : "Operate from reconciled product evidence."}
              </h2>
            </div>
            <span className="panel-status">
              <i aria-hidden="true" /> Fresh registry read
            </span>
          </header>

          {snapshot.products.length === 0 ? (
            <ol className="forge-steps">
              <li>
                <span>01</span>
                <div>
                  <strong>Define the blueprint</strong>
                  <p>Name the outcome and select only required capabilities.</p>
                </div>
              </li>
              <li>
                <span>02</span>
                <div>
                  <strong>Compose the repository</strong>
                  <p>Generate the standalone source and versioned manifest.</p>
                </div>
              </li>
              <li>
                <span>03</span>
                <div>
                  <strong>Return to this control plane</strong>
                  <p>The product appears after a fresh server request.</p>
                </div>
              </li>
            </ol>
          ) : (
            <div className="portfolio-list" role="list">
              {snapshot.products.slice(0, 4).map((product, index) => (
                <Link
                  href={`/dashboard/products/${product.slug}`}
                  key={product.slug}
                  role="listitem"
                >
                  <span>{String(index + 1).padStart(2, "0")}</span>
                  <div>
                    <strong>{product.name}</strong>
                    <small>
                      {product.identitySource === "manifest-verified"
                        ? `${product.modules.length} modules · manifest verified`
                        : "registry-reported · unverified"}
                    </small>
                  </div>
                  <i data-state={product.evidenceState}>
                    {product.evidenceState.replaceAll("-", " ")}
                  </i>
                </Link>
              ))}
            </div>
          )}

          <div className="forge-command">
            <span>RUN FROM THE FACTORY REPOSITORY</span>
            <code>
              pnpm forge:create -- --name &quot;Next Product&quot; --slug
              &quot;next-product&quot; --description &quot;A validated customer
              outcome described clearly.&quot; --modules &quot;auth&quot;
            </code>
          </div>

          <footer className="panel-actions">
            <Link href="/dashboard/products">
              Inspect product registry <span aria-hidden="true">→</span>
            </Link>
            <small>Generation remains an intentional CLI operation.</small>
          </footer>
        </article>

        <article className="dashboard-panel verification-panel">
          <header className="panel-heading">
            <div>
              <p>02 / RECONCILIATION</p>
              <h2>Evidence before claims.</h2>
            </div>
          </header>

          <div className="verification-list">
            {verificationRows.map((row, index) => (
              <div key={row.label}>
                <span>{String(index + 1).padStart(2, "0")}</span>
                <div>
                  <strong>{row.label}</strong>
                  <small>{row.detail}</small>
                </div>
              </div>
            ))}
          </div>

          <div className="signed-in-card">
            <span>AUTHORIZED OPERATOR</span>
            <strong>{session.user.name}</strong>
            <small>{session.user.email}</small>
          </div>
        </article>
      </section>

      <section className="dashboard-lower-grid">
        <article className="dashboard-panel capability-panel">
          <header className="panel-heading compact">
            <div>
              <p>03 / CAPABILITY USE</p>
              <h2>Modules selected across the portfolio.</h2>
            </div>
            <Link href="/dashboard/modules">Inspect modules →</Link>
          </header>
          <div className="capability-table" role="list">
            {capabilities.map((capability, index) => {
              const usage = snapshot.products.filter(
                (product) =>
                  product.identitySource === "manifest-verified" &&
                  product.modules.includes(capability.module),
              ).length;
              return (
                <div
                  data-tone={capability.tone}
                  key={capability.name}
                  role="listitem"
                >
                  <span>{String(index + 1).padStart(2, "0")}</span>
                  <strong>{capability.name}</strong>
                  <small>{capability.code}</small>
                  <i>{usage} USED</i>
                </div>
              );
            })}
          </div>
        </article>

        <article className="dashboard-panel boundary-panel">
          <header className="panel-heading compact">
            <div>
              <p>04 / DATA BOUNDARY</p>
              <h2>Inventory here. Production data there.</h2>
            </div>
          </header>
          <div className="boundary-copy">
            <span aria-hidden="true">SF</span>
            <p>
              This control plane reads local registry and manifest evidence. It
              does not read product secrets, customer records, provider
              payloads, or managed-file fingerprints.
            </p>
          </div>
        </article>
      </section>
    </Container>
  );
}
